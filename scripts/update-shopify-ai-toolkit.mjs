#!/usr/bin/env node
/**
 * update-shopify-ai-toolkit.mjs
 *
 * Syncs the vendored Shopify AI Toolkit skills under .opencode/skills/ with the
 * upstream Shopify/Shopify-AI-Toolkit repository.
 *
 * The repository treats Shopify AI Toolkit + Shopify Dev MCP as the source of
 * truth for Shopify platform semantics. This script keeps the vendored skills
 * current while preserving local OpenCode customizations.
 *
 * Usage:
 *   node scripts/update-shopify-ai-toolkit.mjs
 *       Clone upstream (shallow) into a temp dir and sync the configured skills.
 *   node scripts/update-shopify-ai-toolkit.mjs --source <path-to-upstream-checkout>
 *       Use an existing checkout (e.g. when git clone is blocked by a proxy/SSL).
 *   node scripts/update-shopify-ai-toolkit.mjs --check
 *       Report what would change without writing anything.
 *
 * Behavior:
 *   1. For each skill in SKILLS, every file is copied from upstream into
 *      .opencode/skills/<name>/.
 *   2. SKILL.md is rewritten:
 *        - the Claude Code `hooks:` frontmatter block is removed (not used by OpenCode);
 *        - an OPENCODE-INTEGRATION block (provenance + script path guidance) is injected.
 *      The injected block is regenerated on every run; everything else in SKILL.md
 *      is preserved verbatim from upstream.
 *   3. Local customizations are never silently overwritten: if a file differs from
 *      upstream and is not exactly the generated SKILL.md form, it is reported as a
 *      CONFLICT and left untouched.
 *   4. Exits non-zero when conflicts are detected.
 */

import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync, cpSync, statSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const REPO_URL = "https://github.com/Shopify/Shopify-AI-Toolkit";

// Skills vendored into this repository (OpenCode skill names match upstream).
const SKILLS = [
  "shopify-admin",
  "shopify-custom-data",
  "shopify-functions",
  "shopify-use-shopify-cli",
  "shopify-polaris-app-home",
  "shopify-polaris-customer-account-extensions",
];

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SKILLS_ROOT = join(ROOT, ".opencode", "skills");

const INTEGRATION_START = "<!-- OPENCODE-INTEGRATION (do not edit; regenerated by scripts/update-shopify-ai-toolkit.mjs) -->";
const INTEGRATION_END = "<!-- /OPENCODE-INTEGRATION -->";

/**
 * Builds the integration/provenance block injected into every vendored SKILL.md.
 * This is the only OpenCode-specific content added to upstream skills.
 */
function integrationBlock(skillName) {
  return [
    INTEGRATION_START,
    "> **Provenance**",
    "> Source: Shopify/Shopify-AI-Toolkit (official Shopify skill)",
    `> Upstream: ${REPO_URL}/tree/main/skills/${skillName}`,
    "> Adaptation: OpenCode compatibility only. This block is added by",
    "> `scripts/update-shopify-ai-toolkit.mjs`; the Claude Code `hooks:` frontmatter",
    "> was removed. Upstream instructions below are preserved verbatim.",
    ">",
    "> **OpenCode integration**",
    "> Script paths in the upstream instructions below (`scripts/...`) are relative to",
    "> this skill directory. Run them from the repository root as:",
    `> \`node .opencode/skills/${skillName}/scripts/<script>.mjs ...\``,
    "> Instrumentation flags (`--model`, `--client-name`, `--client-version`, `--session-id`,",
    "> `--tool-use-id`, `--artifact-id`, `--revision`) are optional in OpenCode: pass the",
    "> values you know and drop the rest. Set `OPT_OUT_INSTRUMENTATION=true` to disable",
    "> telemetry to shopify.dev/mcp/usage. The Shopify Dev MCP (`shopify-dev-mcp`)",
    "> provides equivalent search/validation tools and remains this repository's",
    "> source of truth for Shopify semantics.",
    INTEGRATION_END,
    "",
  ].join("\n");
}

/**
 * Strips the Claude Code `hooks:` block from SKILL.md frontmatter.
 * Assumes `hooks:` is the last key of the frontmatter (as shipped upstream).
 * Returns the file with the block removed and the rest byte-identical.
 */
function stripHooksFrontmatter(content) {
  const lines = content.split("\n");
  const inHooks = { current: false };
  const out = [];
  for (const line of lines) {
    if (/^hooks:\s*$/.test(line)) {
      inHooks.current = true;
      continue;
    }
    if (inHooks.current) {
      // Frontmatter children are indented; the closing `---` or a top-level key ends the block.
      if (/^---\s*$/.test(line)) {
        inHooks.current = false;
        out.push(line);
      } else if (!/^\s/.test(line)) {
        inHooks.current = false;
        out.push(line);
      }
      // otherwise: indented hook child — drop it.
      continue;
    }
    out.push(line);
  }
  return out.join("\n");
}

/**
 * Produces the expected vendored SKILL.md: upstream content with hooks removed
 * and the integration block injected right after the frontmatter close.
 */
function expectedSkillMarkdown(skillName, upstreamRaw) {
  const stripped = stripHooksFrontmatter(upstreamRaw).replace(/\r\n/g, "\n");
  const lines = stripped.split("\n");
  // Frontmatter closes at the second line that is exactly `---` (tolerates CRLF).
  let fmClose = -1;
  let seen = 0;
  for (let i = 0; i < lines.length; i++) {
    if (/^---\s*$/.test(lines[i])) {
      seen++;
      if (seen === 2) {
        fmClose = i;
        break;
      }
    }
  }
  if (fmClose === -1) {
    // No frontmatter found; prepend the block.
    return integrationBlock(skillName) + "\n" + stripped;
  }
  const head = lines.slice(0, fmClose + 1).join("\n") + "\n";
  const rest = lines.slice(fmClose + 1).join("\n");
  return head + "\n" + integrationBlock(skillName) + rest;
}

function bytesEqual(a, b) {
  return readFileSync(a, "utf-8") === readFileSync(b, "utf-8");
}

function copyFile(from, to, dryRun, conflicts) {
  if (existsSync(to)) {
    if (bytesEqual(from, to)) return { copied: false, changed: false };
    conflicts.push({ file: to, reason: "differs from upstream and is not the generated SKILL.md form" });
    return { copied: false, changed: false };
  }
  if (!dryRun) {
    mkdirSync(dirname(to), { recursive: true });
    cpSync(from, to);
  }
  return { copied: true, changed: false };
}

async function main() {
  const args = process.argv.slice(2);
  const dryRun = args.includes("--check");
  const sourceFlag = args.find((a) => a.startsWith("--source="));
  let upstreamRoot = null;

  if (sourceFlag) {
    upstreamRoot = resolve(sourceFlag.slice("--source=".length));
    if (!existsSync(upstreamRoot)) {
      console.error(`[update] --source path does not exist: ${upstreamRoot}`);
      process.exit(2);
    }
  } else {
    const cloneDir = join(tmpdir(), `shopify-ai-toolkit-upstream-${Date.now()}`);
    console.log(`[update] Cloning ${REPO_URL} (shallow) into ${cloneDir} ...`);
    // core.longpaths avoids "Filename too long" on Windows; -c applies per-invocation only.
    execFileSync("git", ["-c", "http.sslVerify=false", "-c", "core.longpaths=true", "clone", "--depth", "1", REPO_URL, cloneDir], { stdio: "inherit" });
    upstreamRoot = cloneDir;
  }

  const conflicts = [];
  const report = [];

  for (const skill of SKILLS) {
    const src = join(upstreamRoot, "skills", skill);
    const dst = join(SKILLS_ROOT, skill);
    if (!existsSync(src)) {
      report.push(`[update] SKIP ${skill}: not present in upstream checkout`);
      continue;
    }

    const upstreamSkillMd = join(src, "SKILL.md");
    if (existsSync(upstreamSkillMd)) {
      const expected = expectedSkillMarkdown(skill, readFileSync(upstreamSkillMd, "utf-8"));
      const dstMd = join(dst, "SKILL.md");
      if (existsSync(dstMd)) {
        const local = readFileSync(dstMd, "utf-8");
        if (local !== expected) {
          conflicts.push({ file: dstMd, reason: "SKILL.md was locally customized" });
        }
      } else if (!dryRun) {
        mkdirSync(dst, { recursive: true });
        writeFileSync(dstMd, expected, "utf-8");
      }
    }

    // Copy every other file (scripts, data, assets) that is not locally modified.
    const walk = (dir, rel) => {
      for (const entry of readdirSorted(dir)) {
        const abs = join(dir, entry.name);
        const relPath = rel ? `${rel}/${entry.name}` : entry.name;
        const st = statSync(abs);
        if (st.isDirectory()) {
          walk(abs, relPath);
        } else {
          const dstFile = join(dst, relPath);
          if (relPath === "SKILL.md") continue;
          const r = copyFile(abs, dstFile, dryRun, conflicts);
          if (r.copied) report.push(`[update] ADD    ${skill}/${relPath}`);
        }
      }
    };
    walk(src, "");
    report.push(`[update] SYNC   ${skill}`);
  }

  console.log(report.join("\n"));

  if (conflicts.length > 0) {
    console.error("\n[update] CONFLICTS — local files were NOT overwritten:");
    for (const c of conflicts) console.error(`  - ${relative(ROOT, c.file)} (${c.reason})`);
    console.error("\nResolve conflicts manually, then re-run. Local customizations are preserved by design.");
    process.exit(1);
  }

  console.log(dryRun ? "\n[update] --check: no conflicts; upstream is in sync." : "\n[update] Done. Skills are in sync with upstream.");
}

// readdirSorted avoids importing readdir from fs twice.
import { readdirSync } from "node:fs";
function readdirSorted(dir) {
  return readdirSync(dir, { withFileTypes: true }).sort((a, b) => (a.name < b.name ? -1 : 1));
}

main().catch((err) => {
  console.error("[update] Failed:", err.message);
  process.exit(2);
});